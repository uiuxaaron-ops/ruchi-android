COLOR_RE = re.compile(r'#[0-9A-Fa-f]{6}\b|#[0-9A-Fa-f]{3}\b|\bwhite\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+\s*(?:,\s*[\d.]+\s*)?\)', re.I)

def rgba(c):
    m = re.match(r'rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)', c)
    return tuple(float(x) for x in m.groups(default='1'))
def fa(a): return ('%.3f' % a).rstrip('0').rstrip('.') or '0'

import colorsys
def hexrgb(h):
    h = h.lstrip('#')
    if len(h) == 3: h = ''.join(x * 2 for x in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def lum(rgb): return (.2126 * rgb[0] + .7152 * rgb[1] + .0722 * rgb[2]) / 255
def generic(u, kind):
    """Colours not in the tables: pale tints -> dark translucent tint of the same hue;
    dark text colours -> light version of the same hue."""
    if not u.startswith('#'): return None
    rgb = hexrgb(u); L = lum(rgb)
    hh, ll, ss = colorsys.rgb_to_hls(*[x / 255 for x in rgb])
    if kind in ('bg', 'fill', 'line') and L > .84:
        if max(rgb) - min(rgb) < 14: return '#1F1F22' if kind != 'line' else '#2C2C31'
        r, g, b = [round(x * 255) for x in colorsys.hls_to_rgb(hh, .55, min(1, ss + .3))]
        return 'rgba(%d,%d,%d,%s)' % (r, g, b, '.14' if kind != 'line' else '.3')
    if kind == 'text' and L < .3 and ss > .25:
        r, g, b = [round(x * 255) for x in colorsys.hls_to_rgb(hh, .74, min(1, ss))]
        return '#%02X%02X%02X' % (r, g, b)
    return None

def map_color(c, kind, light_fill=False):
    u = c.upper()
    if u.startswith('RGB'):
        r, g, b, a = rgba(c)
        if (r, g, b) == (255, 255, 255):
            if kind == 'bg': return 'rgba(22,22,24,%s)' % fa(a)
            if kind == 'shadow': return 'rgba(255,255,255,%s)' % fa(min(a * .14, .12))
            if kind == 'line': return 'rgba(255,255,255,%s)' % fa(min(a * .18, .14))
            if kind == 'text': return '#0B0B0C' if light_fill else c
            return 'rgba(22,22,24,%s)' % fa(a)
        if (r, g, b) in ((9, 9, 11), (0, 0, 0), (24, 24, 27)):
            if kind == 'shadow': return 'rgba(0,0,0,%s)' % fa(min(.7, a * 2.6 + .04))
            if kind == 'text': return 'rgba(244,244,245,%s)' % fa(a)
            if kind == 'line': return 'rgba(255,255,255,%s)' % fa(min(.16, a * 1.2))
            if kind in ('bg', 'fill'):
                if (r, g, b) == (0, 0, 0): return c                                 # photo scrims stay black
                if .7 <= a < .9: return 'rgba(244,244,245,%s)' % fa(min(.96, a + .08))  # dark pill -> light pill
                if a <= .14: return 'rgba(255,255,255,%s)' % fa(a * .9)          # subtle fills
                return 'rgba(0,0,0,%s)' % fa(min(.85, a + .25))                   # scrims
        if (r, g, b) == (118, 118, 128): return 'rgba(118,118,128,%s)' % fa(min(.36, a * 2))
        return c
    if kind == 'text': return TXT.get(u, '#0B0B0C' if (light_fill and u in ('#FFF', '#FFFFFF', 'WHITE')) else (generic(u, 'text') or c))
    if kind in ('bg', 'fill') and u not in BG: return generic(u, kind) or c
    if kind == 'line' and u not in LINE and u not in BG: return generic(u, 'line') or c
    if kind in ('line', 'shadow'): return LINE.get(u, BG.get(u, c) if kind == 'line' and u in BG and BG[u].startswith('#') and u not in ('#09090B',) else c)
    return BG.get(u, c)

KIND = {'color': 'text', 'caret-color': 'text', '-webkit-text-fill-color': 'text', 'text-decoration-color': 'text',
        'background': 'bg', 'background-color': 'bg', 'background-image': 'bg', 'fill': 'fill', 'stroke': 'line',
        'box-shadow': 'shadow', 'text-shadow': 'shadow', 'outline': 'line', 'outline-color': 'line', 'filter': 'shadow',
        'border-color': 'line', 'mask': None, '-webkit-mask': None}
def kind_of(prop):
    if prop.startswith('border'): return 'line'
    if prop.startswith('--'):
        n = prop.lower()
        if any(k in n for k in ('edge', 'shadow', 'float')): return 'shadow'
        if any(k in n for k in ('ink', 'mute', 'text', 'fg')): return 'text'
        if 'line' in n: return 'line'
        return 'bg'
    return KIND.get(prop)

def scope(sel):
    sel = sel.strip()
    if not sel: return sel
    if re.match(r'^html\b', sel): return re.sub(r'^html', 'html:where(.dark)', sel, count=1)
    if sel.startswith(':root'): return ':root:where(.dark)' + sel[5:]
    return ':where(html.dark) ' + sel

def split_sel(text):
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch in '([': depth += 1
        elif ch in ')]': depth -= 1
        if ch == ',' and depth == 0: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur); return out

KEEP = ('.thm-pv', '.swt i', '.lgr', '.hcard.glass,#lgbar')   # theme previews + switch knob keep their real colours
ROOT_SKIP = True
def rules(nodes, ind=''):
    global ROOT_SKIP
    out = []
    for n in nodes:
        if n.type == 'qualified-rule':
            sel = tinycss2.serialize(n.prelude).strip()
            if any(k in sel for k in KEEP): continue   # elements that must look the same in both themes
            if ROOT_SKIP and sel == ':root': ROOT_SKIP = False; continue   # tokens are written by hand below
            decls = [d for d in tinycss2.parse_declaration_list(n.content, skip_whitespace=True, skip_comments=True) if d.type == 'declaration']
            vals = {d.lower_name: tinycss2.serialize(d.value).strip() for d in decls}
            bgv = (vals.get('background', '') + vals.get('background-color', '')).replace(' ', '')
            light_fill = 'var(--p1)' in bgv or bool(re.search(r'rgba\(9,9,11,\.(7|8)\d*\)', bgv)) or '#09090B' in bgv.upper()
            body = []
            for d in decls:
                k = kind_of(d.lower_name)
                if not k: continue
                v = tinycss2.serialize(d.value).strip()
                nv = COLOR_RE.sub(lambda m: map_color(m.group(0), k, light_fill), v)
                if d.lower_name == 'color' and light_fill and nv.lower() in ('#fff', '#ffffff', 'white'): nv = 'var(--on-p1)'
                body.append('%s:%s%s' % (d.name, nv, ' !important' if d.important else ''))
            if body:
                out.append(ind + ','.join(scope(x) for x in split_sel(sel)) + '{' + ';'.join(body) + '}')
        elif n.type == 'at-rule' and n.lower_at_keyword in ('media', 'supports') and n.content:
            inner = rules(tinycss2.parse_rule_list(n.content, skip_whitespace=True, skip_comments=True), ind)
            if inner: out.append('@%s %s{\n%s\n}' % (n.lower_at_keyword, tinycss2.serialize(n.prelude).strip(), '\n'.join(inner)))
    return out

