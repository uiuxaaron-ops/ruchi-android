LINE = {k: '#2C2C31' for k in ['#E4E4E7', '#EBEBED', '#F4F4F5', '#EFEFF1', '#F1F1F3', '#E9E9EC', '#D4D4D8', '#E4E6EA', '#FAFAFA']}
