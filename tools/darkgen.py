"""
Ruchi dark theme generator.
Reads every CSS rule in the app's main <style>, and for each colour declaration
writes a dark twin scoped to :where(html.dark) (zero extra specificity) in the
same order, so the cascade behaves exactly like light mode. Output goes between
the DARK-THEME markers in index.html. Re-run after any CSS change:
    python3 tools/darkgen.py index.html
"""
